def annotated(paras):
    """把 paras 渲染成 '[P1] [S1] ... [S2] ...' 的打印格式。"""
    out = []
    for pi, sents in enumerate(paras, 1):
        chunks = [f"[P{pi}]"]
        for si, s in enumerate(sents, 1):
            chunks.append(f"[S{si}] {s}")
        out.append(" ".join(chunks))
    return out


def sent(paras, p, s):
    """按 1-based 的 P/S 取句子。"""
    return paras[p - 1][s - 1]
